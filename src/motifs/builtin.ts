/**
 * Built-in figurative motifs in the spirit of Nari Kunjar patola (women,
 * elephants, parrots, flowers), drawn for this project from traditional folk
 * forms. Format: see format.ts (. ground, 1 primary, 2 secondary, 3 accent,
 * # outline, Z zari).
 */
import { motifFromArt, type MotifGrid } from './format';
import { SYMBOLS, symbolGrid, type SymbolDef } from './symbols';
import { cropToDrawing } from './editing';

export interface BuiltInMotif extends MotifGrid {
  id: string;
  name: string;
  about: string;
  /** False for signs that must never be mirrored (saathiya, Om); figures may face either way. */
  mirrorable?: boolean;
}

export const BUILT_IN_PREFIX = 'builtin:';

function motif(key: string, name: string, about: string, art: string): BuiltInMotif {
  return { id: BUILT_IN_PREFIX + key, name, about, ...motifFromArt(art) };
}

